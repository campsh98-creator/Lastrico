/**
 * Rome: pack every JSON tile as a gzip Data module and point the runtime index at the packed copies.
 * Lossless: each `.bin` inflates to the exact bytes of its JSON tile (SHA-256 in SHA256SUMS.json).
 * The JSON tiles are a reproducible intermediate of build-rome-pilot.mjs and are not versioned;
 * Node reads the packed tiles when they are absent. Keeps the Worker upload below Cloudflare's 64 MiB limit
 * (50 MiB of Rome JSON tiles → about 9 MiB packed). Run after the tiles are generated.
 */
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { createHash } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");

export async function packRomeTiles({
  tilesDir = join(root, "data/surfaces/rome-tiles"),
  packedDir = join(root, "data/surfaces/rome-tiles-packed"),
  indexPath = join(root, "lib/rome-tile-index.ts"),
} = {}) {
  const meta = JSON.parse(await readFile(join(tilesDir, "metadata.json"), "utf8"));
  const keys = meta.tileKeys ?? Object.keys(meta.tiles ?? {});
  if (!keys.length) throw new Error("Rome metadata lists no tiles");
  await rm(packedDir, { recursive: true, force: true });
  await mkdir(packedDir, { recursive: true });
  let jsonBytes = 0;
  let packedBytes = 0;
  // SHA-256 of each original JSON tile: lets tests verify packed tiles without the JSON intermediates.
  const checksums = {};
  for (const key of keys) {
    const json = await readFile(join(tilesDir, `${key}.json`));
    const packed = gzipSync(json, { level: 9 });
    await writeFile(join(packedDir, `${key}.bin`), packed);
    checksums[key] = createHash("sha256").update(json).digest("hex");
    jsonBytes += json.length;
    packedBytes += packed.length;
  }
  await writeFile(join(packedDir, "SHA256SUMS.json"), JSON.stringify({ algorithm: "sha256", of: "original JSON tile bytes", tiles: checksums }, null, 2) + "\n");
  const relative = packedDir.replace(join(root, "data/"), "../data/");
  const index = [
    "// Auto-generated by scripts/osm/pack-rome-tiles.mjs: packed (gzip) Rome tile loaders.",
    'import type { TilePayload } from "./spatial-road-store";',
    'import { inflateTile } from "./rome-tile-codec.ts";',
    "",
    "export const romeTileLoaders: Record<string, () => Promise<{ default: TilePayload }>> = {",
    ...keys.map((key) => `  ${JSON.stringify(key)}: () => import(${JSON.stringify(`${relative}/${key}.bin`)}).then((m) => inflateTile(m.default)),`),
    "};",
    "",
  ].join("\n");
  await writeFile(indexPath, index, "utf8");
  const mib = (bytes) => `${(bytes / 1048576).toFixed(2)} MiB`;
  console.log(`✓ rome: packed ${keys.length} tiles, ${mib(jsonBytes)} JSON → ${mib(packedBytes)} gzip.`);
  return { tiles: keys.length, jsonBytes, packedBytes };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  packRomeTiles().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
